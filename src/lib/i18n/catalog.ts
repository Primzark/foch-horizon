function preserveCase(source: string, translated: string): string {
  if (source === source.toLocaleUpperCase("fr")) return translated.toLocaleUpperCase("en");
  if (source[0] && source[0] === source[0].toLocaleUpperCase("fr")) {
    return translated[0]?.toLocaleUpperCase("en") + translated.slice(1);
  }
  return translated;
}

